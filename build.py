#!/usr/bin/env python3
"""内联核心页面。--site 另生成带同源语音包的静态发布目录（大文件不进 Git）。"""
import argparse
import hashlib
import json
import os
import pathlib
import shutil
import sys
import time
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent
BLOBS = 'https://api.github.com/repos/ccoreilly/vosk-browser/git/blobs/'


def read(name):
    return (ROOT / 'src' / name).read_text(encoding='utf-8')


def escape(code):
    return code.replace('</script', '<\\/script').replace('</style', '<\\/style')


def mirror(item, target):
    if target.exists() and hashlib.sha256(target.read_bytes()).hexdigest() == item['sha256']:
        return
    request = urllib.request.Request(BLOBS + item['blob'], headers={'Accept': 'application/vnd.github.raw+json'})
    # CI runners share IP-based anonymous API limits. Use the job's ephemeral read token
    # only on the fixed API request (not on redirects, and never in the built page).
    if os.environ.get('GITHUB_ACTIONS') == 'true' and os.environ.get('GITHUB_TOKEN'):
        request.add_unredirected_header('Authorization', 'Bearer ' + os.environ['GITHUB_TOKEN'])
    for attempt in range(3):
        try:
            with urllib.request.urlopen(request, timeout=90) as response:
                data = response.read(item['size'] + 1)
            break
        except (OSError, TimeoutError) as error:
            transient = not isinstance(error, urllib.error.HTTPError) or error.code in (408, 429, 500, 502, 503, 504)
            if not transient or attempt == 2:
                raise RuntimeError(f"无法下载 {item['file']}：{error}") from error
            time.sleep(2 ** attempt)
    if len(data) != item['size'] or hashlib.sha256(data).hexdigest() != item['sha256']:
        raise RuntimeError('语音资源校验失败：' + item['file'])
    target.write_bytes(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site', action='store_true', help='准备 dist/（需要首次联网）')
    site = parser.parse_args().site
    out = ROOT / 'dist' if site else ROOT
    files = json.loads(read('voice-pack.json'))
    if site:
        assets = out / 'voice-assets'
        assets.mkdir(parents=True, exist_ok=True)
        for item in files:
            mirror(item, assets / item['file'])
        for name in ['manifest.webmanifest', 'icon.svg', 'icon-180.png', 'icon-512.png']:
            shutil.copyfile(ROOT / name, out / name)
        shutil.copytree(ROOT / 'third_party', out / 'third_party', dirs_exist_ok=True)

    for item in files:
        item['path'] = './voice-assets/' + item['file']
        # 带参数的是用户主动安装的网络请求，无参数路径只读取已校验的副本。
        item['source'] = item['path'] + '?install' if site else BLOBS + item['blob']
    pack = json.dumps(files, separators=(',', ':'))
    store = read('voice-store.js')
    js = store + '\n' + read('offline.js').replace('/*@files*/[]', pack) + '\n' + read('app.js')
    html = read('page.html').replace('<!--@styles-->', '<style>\n' + escape(read('styles.css')) + '  </style>')
    html = html.replace('<!--@app-->', '<script>\n' + escape(js) + '\n  </script>')
    if '<!--@' in html:
        raise SystemExit('还有没替换的占位符')
    (out / 'index.html').write_text(html, encoding='utf-8')
    (out / 'sw.js').write_text('// Generated by build.py from src/voice-store.js and src/sw.js.\n' + store + '\n' + read('sw.js'), encoding='utf-8')
    print(f'{out.name}/index.html  {len(html.encode()) / 1024:.1f} KB')


if __name__ == '__main__':
    try:
        main()
    except (OSError, RuntimeError) as exc:
        if os.environ.get('GITHUB_ACTIONS') == 'true':
            message = str(exc).replace('%', '%25').replace('\r', '%0D').replace('\n', '%0A')
            print('::error title=Site build::' + message)
        sys.exit(str(exc))
